from app.config import settings


def _seller() -> str:
    name = (settings.LEGAL_SELLER_NAME or "").strip()
    details = (settings.LEGAL_SELLER_DETAILS or "").strip()
    if name and details:
        return f"{name}. {details}"
    if name:
        return name
    return "Реквизиты предоставляются по запросу в службу поддержки."


def _contact() -> str:
    value = (settings.SUPPORT_CONTACT or "").strip()
    return value or "Контакты предоставляются по запросу в службу поддержки."


def build_contacts() -> str:
    contact = (settings.SUPPORT_CONTACT or "").strip()
    lines = [
        "КОНТАКТЫ",
        "",
        "Продукт: «D.A.M.N Booking Hub» — облачный сервис автоматизации записи",
        "клиентов в Telegram.",
        "",
        f"Исполнитель: {_seller()}",
        "",
    ]
    if contact:
        lines += [
            f"Поддержка и обращения: {contact}",
            "",
            f"Вопросы по подписке и возврату средств: {contact}",
            "",
            f"Вопросы по персональным данным: {contact}",
        ]
    else:
        lines += [
            "Контакты не указаны. Для подключения оплаты, возврата средств или",
            "вопросов о персональных данных обратитесь к представителю продукта",
            "через Telegram-бота D.A.M.N Booking Hub.",
        ]
    lines += ["", "Правовые документы:", "  Публичная оферта: /offer",
              "  Политика конфиденциальности: /privacy", ""]
    return "\n".join(lines)


def legal_pages() -> dict[str, tuple[str, str]]:
    return {
        "offer": ("Публичная оферта", OFFER),
        "privacy": ("Политика конфиденциальности", PRIVACY),
        "contacts": ("Контакты", build_contacts()),
    }


